import pandas as pd
import streamlit as st

from ..components.kpi_tile import fmt, tile
from ..data.loader import Bundle


def render(b: Bundle) -> None:
    m = b.manifest
    if m:
        s = m.get("summary") or {}
        if s.get("text"):
            st.info(s["text"], icon="📝")
        st.caption(f"run summary ({s.get('source')}, numbers fact-checked: {s.get('fact_check')}) · status {m.get('status')} · "
                   f"{m.get('total_seconds')} s · commit {m.get('git_commit')}")
    st.subheader("Key indicators")
    tiles = b.config.get("tiles")
    cols = st.columns(3)
    if tiles:  # generated by the analyst (dashboard_config.json): latest COMPLETE month
        for i, t in enumerate(tiles):
            with cols[i % 3]:
                good_up = t.get("direction") != "lower_is_better"
                delta = f"{t['delta_pct']:+.1f}% vs previous month" if t.get("delta_pct") is not None else None
                st.metric(t["name"], fmt(t["value"], t.get("unit", "")), delta,
                          delta_color="normal" if good_up else "inverse", help=f"{t['period']} (latest complete month)")
                st.line_chart(pd.DataFrame(t["sparkline"]).set_index("period")["value"], height=70)
    else:
        for i, d in enumerate(b.kpi_defs):
            with cols[i % 3]:
                tile(d, b.values[(b.values.kpi_id == d["id"]) & (b.values.dimension == "total")])
    if m:
        with st.expander("Pipeline stages"):
            st.dataframe(pd.DataFrame([{"stage": k, "status": v["status"], "seconds": v.get("seconds"),
                                        "source": "seeded" if v.get("seeded_from") else ("mock" if v.get("mock") else "real")}
                                       for k, v in m["stages"].items()]), hide_index=True, width="stretch")
    st.caption(f"source: {b.source}" + (f" / run {b.run_id}" if b.run_id else " (demo fixtures)"))
