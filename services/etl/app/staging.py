"""Render the dbt STAGING layer from the dataset YAML (spec BO1: "join SQL rendered from a Jinja template driven
by the dataset YAML"). One stg_<table> view per source table, plus sources.yml and warn-level tests.

Inputs from the YAML:
  source.tables     -> which tables exist (one staging model each)
  expected_schema   -> declared column types  -> CAST
  etl.cast          -> extra casts for columns the cleaner leaves as text (e.g. dates)
  etl.keys          -> grain of each table    -> unique / not_null tests (warn)
  relationships     -> foreign keys           -> relationships tests (warn)

Casts are STRICT (CAST, not TRY_CAST): a value that cannot be converted fails the build loudly instead of
silently becoming NULL. Columns with no declared type pass through unchanged.

Templates use [[ ]] / [% %] delimiters so dbt's own {{ ref(...) }} / {{ source(...) }} pass through untouched.
"""
from __future__ import annotations

from pathlib import Path
from typing import Any

import yaml
from jinja2 import Environment, StrictUndefined

SQL_TYPES = {"str": "VARCHAR", "int": "BIGINT", "float": "DOUBLE", "datetime": "TIMESTAMP", "date": "DATE", "bool": "BOOLEAN"}

_env = Environment(
    variable_start_string="[[", variable_end_string="]]",
    block_start_string="[%", block_end_string="%]",
    undefined=StrictUndefined, trim_blocks=True, lstrip_blocks=True, keep_trailing_newline=True,
)

STG_TEMPLATE = _env.from_string('''-- GENERATED by services/etl/app/staging.py from [[ config_name ]]. Do not edit: change the YAML instead.
-- Staging = one typed view per source table. No joins, no business logic.
select
[% for c in columns %]
    [[ c.expr ]] as [[ c.quoted ]][[ "," if not loop.last ]][% if c.note %]  -- [[ c.note ]][% endif %]

[% endfor %]
from {{ source('raw', '[[ table ]]') }}
''')


def _q(name: str) -> str:
    return '"' + name.replace('"', '""') + '"'


def _declared_types(cfg: dict[str, Any], table: str) -> dict[str, tuple[str, str]]:
    """column -> (logical type, where it was declared)."""
    out: dict[str, tuple[str, str]] = {}
    for col, spec in (cfg.get("expected_schema", {}).get(table) or {}).items():
        out[col] = (spec["type"] if isinstance(spec, dict) else spec, "expected_schema")
    for ref, typ in (cfg.get("etl", {}).get("cast") or {}).items():
        t, col = ref.split(".", 1)
        if t == table:
            out[col] = (typ, "etl.cast")
    return out


def render_model(cfg: dict[str, Any], table: str, columns: list[str], config_name: str) -> str:
    declared = _declared_types(cfg, table)
    cols = []
    for col in columns:
        typ, where = declared.get(col, (None, None))
        if typ and typ not in SQL_TYPES:
            raise ValueError(f"{table}.{col}: unknown type '{typ}' (known: {sorted(SQL_TYPES)})")
        expr = f"cast({_q(col)} as {SQL_TYPES[typ]})" if typ else _q(col)
        cols.append({"expr": expr, "quoted": _q(col), "note": f"{typ} ({where})" if typ else ""})
    return STG_TEMPLATE.render(config_name=config_name, columns=cols, table=table)


def _key_test(cols: list[str]) -> dict[str, Any]:
    if len(cols) == 1:
        return {"unique": {"column_name": _q(cols[0]), "config": {"severity": "warn"}}}
    expr = " || '-' || ".join(f"cast({_q(c)} as varchar)" for c in cols)
    return {"unique": {"column_name": expr, "config": {"severity": "warn"}}}


def render_yaml(cfg: dict[str, Any], tables: list[str]) -> tuple[str, str]:
    """(sources.yml, _staging.yml)."""
    sources = {"version": 2, "sources": [{"name": "raw", "schema": "raw", "tables": [{"name": t} for t in tables]}]}

    models: dict[str, dict[str, Any]] = {t: {"name": f"stg_{t}", "tests": [], "columns": {}} for t in tables}
    for t, key in (cfg.get("etl", {}).get("keys") or {}).items():
        if t in models:
            models[t]["tests"].append(_key_test(key))
            for c in key:
                models[t]["columns"].setdefault(c, []).append({"not_null": {"config": {"severity": "warn"}}})
    for r in cfg.get("relationships", []):
        ct, cc = r["from"].split(".", 1)
        pt, pc = r["to"].split(".", 1)
        if ct in models and pt in tables:
            models[ct]["columns"].setdefault(cc, []).append(
                {"relationships": {"to": f"ref('stg_{pt}')", "field": pc, "config": {"severity": "warn"}}}
            )
    staging = {
        "version": 2,
        "models": [
            {"name": m["name"], "tests": m["tests"], "columns": [{"name": c, "tests": tests} for c, tests in m["columns"].items()]}
            for m in models.values()
        ],
    }
    header = "# GENERATED by services/etl/app/staging.py. Staging tests OBSERVE raw data: severity warn.\n"
    return yaml.safe_dump(sources, sort_keys=False), header + yaml.safe_dump(staging, sort_keys=False)


def write_staging(cfg: dict[str, Any], table_columns: dict[str, list[str]], project_dir: Path, config_name: str) -> list[str]:
    """Write models/staging/* into a dbt project. Returns the staging model names."""
    out = project_dir / "models" / "staging"
    out.mkdir(parents=True, exist_ok=True)
    for t, cols in table_columns.items():
        (out / f"stg_{t}.sql").write_text(render_model(cfg, t, cols, config_name), encoding="utf-8")
    sources_yml, staging_yml = render_yaml(cfg, list(table_columns))
    (out / "_sources.yml").write_text(sources_yml, encoding="utf-8")
    (out / "_staging.yml").write_text(staging_yml, encoding="utf-8")
    return [f"stg_{t}" for t in table_columns]
