"""New-dataset onboarding (mode `suggest_kpis`): table schema -> DRAFT KPI YAML for a human to review. Never executed.

Column roles are inferred by code from a sample (date, measure, binary flag, category, id). From the roles we draft:
  volume (COUNT), sum and average of each measure, rate of each binary flag, all at month grain, with the
  categories as dimensions. Each draft KPI cites the most similar existing KPI (retrieval on the catalog), so the
  reviewer sees "this looks like `revenue`". The LLM (optional) only rewrites names/descriptions, never the SQL.

Input: options.table (fact table name used in the SQL, default fact_<root table>) and the dataset's own CSV source.
Output: runs/<id>/04_kpi/draft_kpis.yaml.
"""
from __future__ import annotations

from pathlib import Path
from typing import Any

import pandas as pd
import yaml

from .common import event, load_dataset, repo_root, stage_dir


def column_roles(df: pd.DataFrame) -> dict[str, str]:
    roles = {}
    for c in df.columns:
        s = df[c].dropna()
        low = c.lower()
        if s.empty:
            roles[c] = "empty"
            continue
        if low.endswith(("_id", "id")) or (s.nunique() > 0.9 * len(s) and not pd.api.types.is_float_dtype(s)):
            roles[c] = "id"
        elif pd.api.types.is_bool_dtype(s) or set(map(str, s.unique())) <= {"0", "1", "Yes", "No", "yes", "no", "True", "False"}:
            roles[c] = "binary"
        elif pd.api.types.is_numeric_dtype(s):
            roles[c] = "measure"
        elif pd.to_datetime(s.astype(str).head(200), errors="coerce").notna().mean() > 0.9 and not s.astype(str).str.fullmatch(r"\d+").all():
            roles[c] = "date"
        elif s.nunique() <= 30:
            roles[c] = "category"
        else:
            roles[c] = "text"
    return roles


def _yes(col: str, values: pd.Series) -> str:
    vals = set(map(str, values.dropna().unique()))
    if vals <= {"0", "1"}:
        return f"CAST({col} AS DOUBLE)"
    pos = next((v for v in ("Yes", "yes", "True", "true", "1") if v in vals), sorted(vals)[-1])
    return f"CAST({col} = '{pos}' AS DOUBLE)"


def draft(cfg: dict[str, Any], table: str | None = None) -> dict[str, Any]:
    src = repo_root() / cfg["source"]["path"]
    root = next(iter(cfg["source"]["tables"]))
    df = pd.read_csv(src / cfg["source"]["tables"][root], nrows=5000)
    roles = column_roles(df)
    fact = table or f"fact_{root}"
    dates = [c for c, r in roles.items() if r == "date"]
    period = f"date_trunc('month', CAST({dates[0]} AS TIMESTAMP))" if dates else "'all'"
    dims = [c for c, r in roles.items() if r == "category"][:6]

    def kpi(kid: str, name: str, expr: str, unit: str, desc: str) -> dict[str, Any]:
        return {"id": kid, "name": name, "description": desc,
                "sql": f"SELECT {period} AS period, {expr} AS value FROM {fact} GROUP BY 1",
                "grain": "month" if dates else "all", "unit": unit, "direction": "neutral", "dimensions": dims,
                "synonyms": [], "draft_from_columns": [c for c in df.columns if c in expr] or ["*"]}

    drafts = [kpi(f"{root}_count", f"Number of {root}", "COUNT(*)", "count", f"Rows in {fact} per month.")]
    for c in [c for c, r in roles.items() if r == "measure"][:8]:
        drafts.append(kpi(f"total_{c.lower()}", f"Total {c}", f"SUM({c})", "number", f"Sum of {c}."))
        drafts.append(kpi(f"avg_{c.lower()}", f"Average {c}", f"AVG({c})", "number", f"Mean of {c}."))
    for c in [c for c, r in roles.items() if r == "binary"][:6]:
        drafts.append(kpi(f"{c.lower()}_rate", f"{c} rate", f"AVG({_yes(c, df[c])})", "ratio", f"Share of rows where {c} is positive."))
    return {"roles": roles, "fact_table": fact, "period_column": dates[0] if dates else None, "dimensions": dims, "kpis": drafts}


def suggest_kpis(req: Any) -> dict[str, Any]:
    cfg = load_dataset(req.config_ref, req.dataset)
    d = draft(cfg, req.options.get("table"))
    try:  # cite the closest existing KPI for each draft (retrieval only, no LLM)
        from .retrieval import retrieve

        base_ref = req.options.get("reference_dataset", "configs/datasets/olist.yaml")
        base_cfg = load_dataset(base_ref, "olist")
        for k in d["kpis"]:
            top, _ = retrieve(base_cfg, f"{k['name']}. {k['description']}", k=1)
            k["similar_existing_kpi"] = top[0]["kpi_id"] if top else None
    except Exception as e:  # noqa: BLE001
        d["warning"] = f"similarity lookup skipped: {type(e).__name__}"
    out_dir, rel = stage_dir(req.run_id, "04_kpi")
    header = ("# DRAFT generated by semantic_kpi.suggest_kpis. Review every entry before copying it into configs/kpis/.\n"
              f"# Inferred column roles: {d['roles']}\n")
    Path(out_dir / "draft_kpis.yaml").write_text(header + yaml.safe_dump(d["kpis"], sort_keys=False), encoding="utf-8")
    return {"status": "ok",
            "outputs": [{"name": "draft_kpis", "kind": "json", "path": f"{rel}/draft_kpis.yaml", "label": "draft KPI YAML (review)"}],
            "metrics": {"draft_kpis": len(d["kpis"]), "roles": d["roles"], "dimensions": d["dimensions"]},
            "lineage_events": [event(req.run_id, "suggest_kpis", rule="column roles -> draft KPI templates",
                                     rows_affected=len(d["kpis"]), params={"fact_table": d["fact_table"]})]}
